const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const html=read('index.html'),favorites=read('favorites.js'),model=read('favorites-model.js');
for(const name of ['id="favImport"','id="favPrintWizard"','setup-print-parser.js','setup-print-import.js','setup-print-ui.css','ui-compact-5512.css'])assert.ok(html.includes(name),name);
assert.ok(html.indexOf('setup-print-parser.js')<html.indexOf('setup-print-import.js'));
assert.ok(html.indexOf('setup-print-import.js')<html.indexOf('favorites.js?v='));
assert.match(read('garage-plus.js'),/window\.GBRGaragePlus=\{parseOCR,loadOCR/);
assert.match(favorites,/window\.GBRSetupPrint\?\.open/);
assert.match(favorites,/mode='new';render\(\)/);
assert.match(favorites,/window\.GBRSetupPrint\?\.close/);
assert.match(model,/const MAX=8;/);
assert.ok(!read('setup-print-import.js').includes('fetch('));
assert.ok(!read('setup-print-import.js').includes('localStorage'));
assert.ok(!read('setup-print-import.js').includes('scheduleSave'));
assert.ok(!read('setup-print-parser.js').includes('owned=true'));
const dashboard=html.slice(html.indexOf('id="dashboard"'),html.indexOf('id="builder"'));
assert.ok(dashboard.includes('ATALHOS DO LAB'));
assert.ok(!dashboard.includes('VER EQUIPES'));
console.log('OK: importador instalado, fluxo não grava antes da revisão, regras e painel preservados.');
