/* 5.5.12 — importação de prints não cria cartas nem inventa atributos. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const folder=path.resolve(__dirname,'..');
const ctx={window:{}};vm.createContext(ctx);
for(const file of ['legendary-drivers.js','setup-print-parser.js'])vm.runInContext(fs.readFileSync(path.join(folder,file),'utf8'),ctx,{filename:file});
const parser=ctx.window.GBRSetupPrintParser;
const cats=Array.from(parser.categories);
const names=['Bounce','Hotfix','Dominus','Leading Edge','Pressure Point','Powerbox','Energy Reserve'];
const garage={parts:cats.map((category,i)=>({id:'p'+i,name:names[i],category,owned:true,level:i+1,rarity:'Epic',speed:10+i})),drivers:[{id:'d1',name:'Senna',owned:true,rarity:'Legendary'},{id:'d2',name:'Fangio',owned:true,rarity:'Legendary'}]};
const carText='CONFIGURAÇÕES DE EQUIPE 3 CARRoS Leading Edge 7 215/400 Pressure Point 4 27/50 Bounce 5 31/100 Dominus 4 26/50 Powerbox 3 8/20 Hotfix 6 190/200 Energy Reserve 7 148/400 Velocidade 175 Curvas 113 Pit stop 3.20';
const driverText='PILOTOS 1 A. Senna 5/4 J. M. Fangio 3/10 Ultrapassagem 80 Defesa 71';
const result=parser.reconcile(carText,driverText,garage,ctx.window.GBRLegendaryDrivers.all);
assert.equal(result.ready,true,'Os 7 nomes e a dupla devem ser resolvidos');
assert.equal(Object.values(result.partIds).filter(Boolean).length,7);
assert.equal(result.partIds['Asa dianteira'],'p3');
assert.equal(result.partIds['Motor'],'p1');
assert.equal(result.driverIds[0],'d1');
assert.equal(result.driverIds[1],'d2');
assert.equal(garage.parts[0].level,1,'O parser não altera nível');
assert.equal(garage.parts[0].owned,true,'O parser não altera posse');
const noDrivers=parser.reconcile(carText,'',garage,ctx.window.GBRLegendaryDrivers.all);
assert.equal(noDrivers.ready,false);assert.deepEqual([...noDrivers.driverIds],['','']);
const unowned={...garage,parts:garage.parts.map((p,i)=>i===3?{...p,owned:false}:p)};
const notOwned=parser.reconcile(carText,driverText,unowned,ctx.window.GBRLegendaryDrivers.all);
assert.equal(notOwned.partIds['Asa dianteira'],'','Peça não possuída não pode ser selecionada');
assert.equal(notOwned.ready,false);
const ambiguous={...garage,parts:[...garage.parts,{...garage.parts[3],id:'second-leading-edge'}]};
const uncertainty=parser.reconcile(carText,driverText,ambiguous,ctx.window.GBRLegendaryDrivers.all);
assert.equal(uncertainty.partIds['Asa dianteira'],'','Duas raridades/versões da mesma peça exigem revisão');
const hillGarage={parts:[],drivers:[{id:'graham',name:'Graham Hill',owned:true},{id:'damon',name:'Damon Hill',owned:true}]};
const hill=parser.scan('G. Hill e D. Hill',hillGarage.drivers,'drivers',ctx.window.GBRLegendaryDrivers.all);
assert.deepEqual(Array.from(hill,x=>x.id),['graham','damon']);
const onlyD=parser.scan('D. Hill e Prost',hillGarage.drivers,'drivers',ctx.window.GBRLegendaryDrivers.all);
assert.deepEqual(Array.from(onlyD,x=>x.id),['damon']);
assert.equal(parser.scan('Não selecionar qualquer nome escondido em prefixos',garage.drivers,'drivers').length,0);
assert.equal(parser.scan('<script>alert(1)</script>',garage.parts,'parts').length,0);
console.log('OK: parser de prints, 7 peças, 2 pilotos, aliases, exclusões, ambiguidades e não-posse.');
